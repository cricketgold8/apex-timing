import { scheduleState, SEASON_2026 } from "@/lib/config/season-2026";
import { ok } from "@/lib/server/respond";

/** The validated 2026 calendar with each session's position relative to its scheduled window. */
export async function GET() {
  const now = new Date();
  return ok(
    {
      data: SEASON_2026.events.map((e) => ({ ...e, sessions: e.sessions.map((s) => ({ ...s, state: scheduleState(s, now) })) })),
      provenance: {
        provider: "OpenF1 + Jolpica-F1 (calendar snapshot)",
        mode: "HISTORICAL",
        sessionId: null,
        sourceTimestamp: SEASON_2026.generatedAt,
        fetchedAt: now.toISOString(),
        completeness: "complete",
        notes: [`Generated by scripts/sync-season.mjs from: ${SEASON_2026.sources.join(", ")}`, ...SEASON_2026.warnings],
      },
    },
    300,
  );
}
